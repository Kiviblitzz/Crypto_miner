// Saisonale Außentemperatur-Abweichung (°C) – Nordhalbkugel
export function seasonOffset(day) {
  const d = dayToDate(day);
  const doy = (d - Date.UTC(d.getUTCFullYear(), 0, 1)) / DAY_MS;
  return -Math.cos(((doy - 15) / 365) * Math.PI * 2) * 3.5 + 0.5 + (inHeatwave(day) ? 6 : 0);
}

// Deterministisches Rauschen für tägliche Kursschwankung
export function noise(day, seed = 1) {
  let s = 0, amp = 1, tot = 0;
  for (const p of [3, 7, 17]) {
    const i = Math.floor(day / p), f = (day / p) - i;
    const h = (n) => { const x = Math.sin(n * 127.1 + seed * 311.7) * 43758.5453; return x - Math.floor(x); };
    const a = h(i), b = h(i + 1);
    const u = f * f * (3 - 2 * f);
    s += (a + (b - a) * u - 0.5) * amp; tot += amp; amp *= 0.6;
  }
  return s / tot;
}
