// Historische Stützpunkte (gerundet). Quellen: siehe docs/RECHERCHE.md
// Alle Werte werden log-linear zwischen den Stützpunkten interpoliert.

export const DAY_MS = 86400000;
export const toDay = (s) => {
  const [y, m, d] = s.split('-').map(Number);
  return Math.floor(Date.UTC(y, (m || 1) - 1, d || 15) / DAY_MS);
};
export const dayToDate = (day) => new Date(day * DAY_MS);

// Kurve: [['YYYY-MM(-DD)', wert], ...] -> Funktion(dayNumber) => wert
export function curve(points, { log = true, after = 'hold' } = {}) {
  const pts = points.map(([d, v]) => [toDay(d), v]).sort((a, b) => a[0] - b[0]);
  const f = (day) => {
    if (day <= pts[0][0]) return pts[0][1];
    const last = pts[pts.length - 1];
    if (day >= last[0]) return last[1];
    let lo = 0, hi = pts.length - 1;
    while (hi - lo > 1) { const mid = (lo + hi) >> 1; if (pts[mid][0] <= day) lo = mid; else hi = mid; }
    const [d0, v0] = pts[lo], [d1, v1] = pts[hi];
    const t = (day - d0) / (d1 - d0);
    if (log && v0 > 0 && v1 > 0) return Math.exp(Math.log(v0) + (Math.log(v1) - Math.log(v0)) * t);
    return v0 + (v1 - v0) * t;
  };
  f.lastDay = pts[pts.length - 1][0];
  f.firstDay = pts[0][0];
  return f;
}

// Stufenfunktion (z.B. Blockbelohnung)
export function steps(points) {
  const pts = points.map(([d, v]) => [toDay(d), v]).sort((a, b) => a[0] - b[0]);
  return (day) => { let v = pts[0][1]; for (const [d, x] of pts) { if (day >= d) v = x; else break; } return v; };
}

